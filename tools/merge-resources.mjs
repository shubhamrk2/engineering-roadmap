/* Merges tools/resources/*.json into assets/js/day-resources.js and reports coverage.

   Usage:   node tools/merge-resources.mjs            write assets/js/day-resources.js, print coverage
            node tools/merge-resources.mjs --check    print coverage only, write nothing

   Every file under tools/resources/ has the shape { "days": { "<day>": { "text": [...], "video": [...] } } }.
   Files named *dsa* go to the per-day "dsa" bucket (the 45-minute DSA block); everything else goes to the
   main per-day bucket. Duplicate URLs within a bucket are dropped. The plan itself (assets/js/daily-plan.js)
   is the authority on how many days exist and which of them have a DSA block.                              */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

// read the plan the same way the browser does
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(readFileSync(join(root, 'assets/js/daily-plan.js'), 'utf8'), ctx);
const weeks = ctx.window.WEEKS;
const plan = [];
weeks.forEach(w => w.days.forEach(d => plan.push({ n: plan.length + 1, theme: d.t, hasDsa: !!d.s })));

const dir = join(root, 'tools/resources');
const files = readdirSync(dir).filter(f => f.endsWith('.json')).sort();
const out = {};
const slot = (n, bucket) => { out[n] ??= {}; out[n][bucket] ??= { text: [], video: [] }; return out[n][bucket]; };
const seen = new Set();
const problems = [];

for (const f of files) {
  let j;
  try { j = JSON.parse(readFileSync(join(dir, f), 'utf8')); } catch (e) { problems.push(`${f}: invalid JSON (${e.message})`); continue; }
  const bucket = /dsa/i.test(f) ? 'dsa' : 'main';
  for (const [day, v] of Object.entries(j.days || {})) {
    const n = Number(day);
    if (!(n >= 1 && n <= plan.length)) { problems.push(`${f}: day ${day} is outside 1-${plan.length}`); continue; }
    for (const kind of ['text', 'video']) {
      for (const r of v[kind] || []) {
        if (!r.u || !r.t) { problems.push(`${f} day ${day}: entry missing t or u`); continue; }
        if (kind === 'video' && !/youtube\.com\/watch\?v=|youtu\.be\//.test(r.u)) { problems.push(`${f} day ${day}: video link is not a specific video: ${r.u}`); continue; }
        const key = `${n}|${bucket}|${r.u}`;
        if (seen.has(key)) continue;
        seen.add(key);
        const e = { t: r.t, u: r.u };
        if (r.why) e.why = r.why;
        if (r.by) e.by = r.by;
        slot(n, bucket)[kind].push(e);
      }
    }
  }
}

// reshape: { "12": { text, video, dsa:{text,video} } }
const final = {};
for (const [n, b] of Object.entries(out)) {
  final[n] = { text: b.main?.text || [], video: b.main?.video || [] };
  if (b.dsa) final[n].dsa = b.dsa;
}

// coverage
let noText = [], noVideo = [], noDsaText = [], noDsaVideo = [];
for (const p of plan) {
  const b = final[p.n] || { text: [], video: [] };
  if (!b.text.length) noText.push(p.n);
  if (!b.video.length) noVideo.push(p.n);
  if (p.hasDsa) {
    if (!(b.dsa?.text?.length)) noDsaText.push(p.n);
    if (!(b.dsa?.video?.length)) noDsaVideo.push(p.n);
  }
}
const fmt = a => (a.length ? a.join(', ') : 'none');
console.log(`files merged: ${files.join(', ') || '(none)'}`);
console.log(`days in plan: ${plan.length}; days with a DSA block: ${plan.filter(p => p.hasDsa).length}`);
console.log(`days with no TEXT resource:  ${noText.length}  -> ${fmt(noText)}`);
console.log(`days with no VIDEO resource: ${noVideo.length}  -> ${fmt(noVideo)}`);
console.log(`DSA days with no text:       ${noDsaText.length}  -> ${fmt(noDsaText)}`);
console.log(`DSA days with no video:      ${noDsaVideo.length}  -> ${fmt(noDsaVideo)}`);
if (problems.length) console.log('\nproblems:\n  ' + problems.join('\n  '));

if (!checkOnly) {
  const js = '/* Generated by tools/merge-resources.mjs from tools/resources/*.json. Do not edit by hand. */\n' +
    'window.DAYRES = ' + JSON.stringify(final) + ';\n';
  writeFileSync(join(root, 'assets/js/day-resources.js'), js);
  console.log(`\nwrote assets/js/day-resources.js (${Object.keys(final).length} days, ${(js.length / 1024).toFixed(0)} KB)`);
}
process.exit(problems.length ? 1 : 0);
